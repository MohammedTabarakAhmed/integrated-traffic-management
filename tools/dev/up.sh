#!/usr/bin/env bash
# One-command local startup (BRD reader's guide: "README that starts the whole system with one command").
#   tools/dev/up.sh          build + start PostgreSQL, Keycloak (realm "itms") and reference-data-service
#   tools/dev/up.sh down     stop the stack (data volume kept)
# First run generates infra/local/.env with random development secrets (git-ignored; SEC-004).
set -euo pipefail
cd "$(dirname "$0")/../.."
ENV_FILE=infra/local/.env
COMPOSE=(docker compose -f infra/local/compose.yaml --env-file "$ENV_FILE")
PY=${PYTHON:-python3}; command -v "$PY" >/dev/null || PY=python

if [[ "${1:-}" == "down" ]]; then
  "${COMPOSE[@]}" down
  exit 0
fi

if [[ ! -f "$ENV_FILE" ]]; then
  echo "== Generating $ENV_FILE with random development secrets"
  "$PY" - "$ENV_FILE" <<'PYEOF'
import secrets, sys
values = {
    "REFDATA_DB_USER": "refdata",
    "REFDATA_DB_PASSWORD": secrets.token_urlsafe(24),
    "KC_ADMIN_USER": "kc-admin",
    "KC_ADMIN_PASSWORD": secrets.token_urlsafe(24),
    "DEV_MAKER_PASSWORD": secrets.token_urlsafe(16),
    "DEV_CHECKER_PASSWORD": secrets.token_urlsafe(16),
}
with open(sys.argv[1], "w", encoding="utf-8") as f:
    f.write("# LOCAL DEVELOPMENT ONLY. Generated by tools/dev/up.sh. Never commit.\n")
    for k, v in values.items():
        f.write(f"{k}={v}\n")
PYEOF
fi
set -a; source "$ENV_FILE"; set +a

echo "== Building service jar"
mvn -B -ntp -q package -DskipTests -pl services/reference-data-service -am

echo "== Starting stack (this waits until every container is healthy)"
"${COMPOSE[@]}" up -d --build --wait

echo "== Setting development user passwords in Keycloak"
# MSYS_NO_PATHCONV stops Git Bash on Windows from rewriting the container path /opt/... (scoped to this call only).
KC=(env MSYS_NO_PATHCONV=1 docker compose -f infra/local/compose.yaml --env-file "$ENV_FILE" exec -T keycloak /opt/keycloak/bin/kcadm.sh)
"${KC[@]}" config credentials --server http://localhost:8080 --realm master \
  --user "$KC_ADMIN_USER" --password "$KC_ADMIN_PASSWORD" >/dev/null
"${KC[@]}" set-password -r itms --username dev.maker --new-password "$DEV_MAKER_PASSWORD"
"${KC[@]}" set-password -r itms --username dev.checker --new-password "$DEV_CHECKER_PASSWORD"

cat <<EOF

ITMS local stack is up:
  reference-data-service  http://localhost:8081/v1/reference-lists   (bearer token required)
  Keycloak                http://localhost:8180   (realm: itms; users dev.maker / dev.checker; passwords in $ENV_FILE)
Smoke test:               tools/dev/smoke.sh
Stop:                     tools/dev/up.sh down
EOF
